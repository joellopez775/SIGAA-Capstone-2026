def color(s):
 if s.startswith('#'):
  if len(s)==9:return colors.Color(int(s[1:3],16)/255,int(s[3:5],16)/255,int(s[5:7],16)/255,alpha=int(s[7:9],16)/255)
  return colors.HexColor(s)
 return colors.toColor(s)

def ops(items):
 C.saveState();face='Helvetica';size=10;bold=False
 for o in items:
  op=o['op']
  if op=='c':C.setStrokeColor(color(o['color']));C.setFillColor(color(o['color']))
  elif op=='C':C.setFillColor(color(o['color']))
  elif op=='F':size=o['size'];face='Helvetica';C.setFont(face,size)
  elif op=='t':bold=bool(o.get('fontchar',0)&1);face='Helvetica-Bold' if bold else 'Helvetica';C.setFont(face,size)
  elif op=='S':
   s=o['style'];C.setDash(4,3) if s=='dashed' else C.setDash();
   if s.startswith('setlinewidth('):C.setLineWidth(float(s[13:-1]))
  elif op in ['P','p','L','b','B']:
   pts=o['points'];path=C.beginPath();path.moveTo(*pts[0])
   if op in ['b','B']:
    for i in range(1,len(pts),3):path.curveTo(*(pts[i]+pts[i+1]+pts[i+2]))
   else:
    for pt in pts[1:]:path.lineTo(*pt)
   if op in ['P','p']:path.close()
   C.drawPath(path,stroke=1,fill=op in ['P','B'])
  elif op in ['e','E']:
   x,y,rx,ry=o['rect'];C.ellipse(x-rx,y-ry,x+rx,y+ry,fill=op=='E',stroke=1)
  elif op=='T':
   x,y=o['pt'];text=o['text'];tw=pdfmetrics.stringWidth(text,face,size);allocated=o['width'];x-=allocated/2 if o['align']=='c' else allocated if o['align']=='r' else 0
   C.saveState();C.translate(x,y);C.scale(allocated/tw if tw else 1,1);C.drawString(0,0,text);C.restoreState()
  else:raise RuntimeError('Unsupported Graphviz operation '+op)
 C.restoreState()

