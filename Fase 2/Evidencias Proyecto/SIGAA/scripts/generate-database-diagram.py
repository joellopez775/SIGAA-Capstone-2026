def node(name,mode):
 t=T[name];pk={n for k in t['constraints'] if k['type']=='p' for n in k['columns']};fks={c:[f['ref'] for f in D['foreign_keys'] if f['source']==name and c in f['source_columns']] for c in [c['name'] for c in t['columns']]};u={x['columns'][0] for x in t['indexes'] if x['unique'] and x['predicate'] is None and len(x['columns'])==1 and not x['primary']}
 stub=mode=='stub';cols=[c for c in t['columns'] if mode=='full' or c['name'] in pk or (mode=='overview' and fks[c['name']])]
 color='#78877d' if stub else PALETTE[TABLEGROUP[name]]
 rows=[f'<TR><TD COLSPAN="3" BGCOLOR="{color}"><FONT COLOR="white" POINT-SIZE="12"><B>{name}</B></FONT></TD></TR>']
 if stub:rows.append('<TR><TD COLSPAN="3" BGCOLOR="#f2f4f1"><FONT POINT-SIZE="9">Referencia a otro módulo</FONT></TD></TR>')
 for c in cols:
  n=c['name'];flags=[]
  if n in pk:flags.append('PK')
  if n in u:flags.append('U')
  flags+=fks[n]
  typ=c['type'].replace('timestamp with time zone','timestamptz').replace('character varying','varchar');flags.append('?' if c['nullable'] else '!')
  rows.append('<TR>'+''.join(f'<TD ALIGN="LEFT">{escape(v)}</TD>' for v in [n,typ,' '.join(flags)])+'</TR>')
 return f'"{name}" [label=<<TABLE BORDER="1" CELLBORDER="0" CELLSPACING="0" CELLPADDING="5" COLOR="{color}">'+''.join(rows)+'</TABLE>>];'

def graph(filename,own,overview=False):
 fs=[f for f in D['foreign_keys'] if f['source'] in own];targets={f['target'] for f in fs};names=set(own)|targets
 lines=['digraph SIGAA {','graph [rankdir=LR, bgcolor="transparent", nodesep=0.55, ranksep=1.3, splines=polyline, pad=0.3, outputorder=edgesfirst];','node [shape=plain, fontname="Helvetica", fontsize=10];','edge [fontname="Helvetica", fontsize=9, color="#82968b", fontcolor="#314f40", arrowsize=0.65];']
 for name in sorted(names):lines.append(node(name,'overview' if overview else 'full' if name in own else 'stub'))
 for f in fs:
  # Constraint ids label every relationship; the register spells out its columns.
  lines.append(f'"{f["source"]}" -> "{f["target"]}" [label="{f["ref"]}  {f["child_cardinality"]} : {f["parent_cardinality"]}", style="'+('dashed' if f['parent_cardinality']=='0..1' else 'solid')+'"];')
 lines.append('}');(DIR/(filename+'.dot')).write_text('\n'.join(lines)+'\n')
 return {'file':filename,'tables':sorted(own),'relations':[f['ref'] for f in fs]}

